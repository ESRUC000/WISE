def save_device_snapshot(user_id, snapshot):
    scanned_at = datetime.now().astimezone().isoformat(timespec="seconds")
    devices = [dict(device) for device in snapshot.get("devices", [])]
    with closing(_connect()) as connection, connection:
        previous = connection.execute(
            "SELECT devices_json FROM device_snapshots WHERE user_id = ? ORDER BY scanned_at DESC, id DESC LIMIT 1",
            (user_id,),
        ).fetchone()
        has_previous = previous is not None
        known_macs = set()
        if previous:
            known_macs = {str(device.get("mac", "")).casefold()
                          for device in json.loads(previous["devices_json"])}
        for device in devices:
            mac = str(device.get("mac", "")).casefold()
            device["is_new"] = bool(has_previous and mac and mac != "unknown" and mac not in known_macs)
        values = (user_id, scanned_at, str(snapshot.get("interface", "Unknown")),
                  str(snapshot.get("subnet", "Unknown")), snapshot.get("gateway_ip"),
                  json.dumps(devices, ensure_ascii=False))
        cursor = connection.execute(
            "INSERT INTO device_snapshots (user_id, scanned_at, interface, subnet, gateway_ip, devices_json) "
            "VALUES (?, ?, ?, ?, ?, ?)" + (" RETURNING id" if DATABASE_URL else ""), values,
        )
        snapshot_id = cursor.fetchone()["id"] if DATABASE_URL else cursor.lastrowid
        cursor.close()
    return {"id": snapshot_id, "scanned_at": scanned_at, "interface": values[2],
            "subnet": values[3], "gateway_ip": values[4], "devices": devices}


def latest_device_snapshot(user_id):
    with closing(_connect()) as connection:
        row = connection.execute(
            "SELECT * FROM device_snapshots WHERE user_id = ? ORDER BY scanned_at DESC, id DESC LIMIT 1",
            (user_id,),
        ).fetchone()
    if row is None:
        return None
    result = dict(row)
    result["devices"] = json.loads(result.pop("devices_json"))
    return result
